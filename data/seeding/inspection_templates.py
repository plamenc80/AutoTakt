def create_templates(services):
    """Създава шаблоните; предложената услуга се намира по ключова дума в името (без пакетите)."""
    from data.models import InspectionTemplate, InspectionTemplateItem

    singles = [s for s in services if not s.is_package]

    def find(keyword):
        return next((s for s in singles if keyword and keyword.lower() in s.name.lower()), None)

    created = []
    for name, description, scale, items in TEMPLATES:
        template = InspectionTemplate.objects.create(name=name, description=description, scale=scale)
        for order, row in enumerate(items, start=1):
            section, item_name, kind, *rest = row
            hint, keyword, unit, warn, fail = (rest + [None] * 5)[:5]
            InspectionTemplateItem.objects.create(
                template=template, section=section, name=item_name, type=kind, hint=hint, unit=unit,
                warn_below=D(warn) if warn else None, fail_below=D(fail) if fail else None,
                suggested_service=find(keyword), sort_order=order * 10)
        created.append(template)
    return created
